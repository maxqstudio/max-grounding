def run_fixture(skill_root: Path, profile: str, *, generated: bool, sequence: bool) -> None:
    with tempfile.TemporaryDirectory(prefix=f"skill-workflow-{profile}-adoption-") as td:
        root = Path(td)
        write(root / "PROJECT_PROFILE.yaml", profile_text(profile, generated=generated, sequence=sequence))
        seed_specs(root)
        seed_docs(root, profile, generated=generated, sequence=sequence)

        parsed = parse_profile(root / "PROJECT_PROFILE.yaml")
        failures = validate_profile(parsed)
        if failures:
            raise RuntimeError(f"{profile} profile invalid: {failures}")

        proc = subprocess.run(
            [sys.executable, str(skill_root / "scripts" / "validate_handoff.py"), "--root", str(root)],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            check=False,
        )
        if proc.returncode != 0 or f"RESULT=PASS profile={profile}" not in proc.stdout:
            raise RuntimeError(f"{profile} adoption fixture failed\n{proc.stdout}")
        print(f"{profile.upper()}_ADOPTION_FIXTURE=PASS")


def main() -> int:
    skill_root = Path(__file__).resolve().parent.parent
    run_fixture(skill_root, "lite", generated=False, sequence=False)
    run_fixture(skill_root, "standard", generated=True, sequence=True)
    print("STRICT_ADOPTION_FIXTURE=PERMANENT_STRICT_E2E_LANE")
    print("ADOPTION_PROFILE_MATRIX=PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
