#!/usr/bin/env python3
"""Representative LITE and STANDARD adoption fixtures for SW2-08."""

from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

from project_profile import parse_profile, validate_profile


MARKER = "<!-- GENERATED BY PROJECT TRUTH COMPILER - DO NOT EDIT -->\n"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def profile_text(profile: str, *, generated: bool, sequence: bool) -> str:
    return f"""schema_version: 1
profile: {profile}

contracts:
  api_contracts: optional
  data_contracts: optional
  ui_information_architecture: optional
  runbook: optional
  decisions: optional
  known_defects: optional
  glossary: optional
  changelog: optional

runtime:
  e2e_required: false

documentation:
  generated: {'true' if generated else 'false'}
  spec_root: .workflow
  docs_root: docs

sequence:
  required: {'true' if sequence else 'false'}
  runtime_trace_required: false

notes:
  profile_reason: sw2_08_{profile}_adoption_fixture
"""


def seed_specs(root: Path) -> None:
    write(
        root / ".workflow" / "roadmap.json",
        '{"schema_version":1,"current_phase":"ADOPTION","phases":[{"id":"ADOPTION","title":"Adoption fixture","status":"CURRENT","objective":"Validate profile adoption.","exit_criteria":["Structural handoff passes."]}]}\n',
    )
    write(
        root / ".workflow" / "state.json",
        '{"schema_version":1,"phase":"ADOPTION","status":"IN_PROGRESS","working_branch":"fixture","last_accepted_sha":"","last_accepted_branch":"","proven":[],"not_proven":[],"blockers":[],"next_authorized_actions":[],"blocked_actions":[]}\n',
    )


def doc(text: str, generated: bool) -> str:
    return (MARKER if generated else "") + text


